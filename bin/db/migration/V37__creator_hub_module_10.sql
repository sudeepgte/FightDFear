CREATE TABLE IF NOT EXISTS creator_reviews (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    creator_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    rating INT,
    review_text VARCHAR(2000),
    created_at DATETIME,
    CONSTRAINT fk_creator_review_creator FOREIGN KEY (creator_id) REFERENCES `user`(id),
    CONSTRAINT fk_creator_review_user FOREIGN KEY (user_id) REFERENCES `user`(id)
);
