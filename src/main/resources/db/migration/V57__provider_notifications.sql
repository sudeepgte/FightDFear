    bank_details VARCHAR(255) NULL,
    payout_balance DOUBLE NULL,
    payout_requested_at DATETIME NULL,
    gallery_photos TEXT NULL,
    profile_image_url VARCHAR(255) NULL,
    profile_photo VARCHAR(255) NULL,
    business_name VARCHAR(255) NULL,
    service_area VARCHAR(255) NULL,
    qualification VARCHAR(255) NULL,
    experience VARCHAR(255) NULL,
    available_days VARCHAR(255) NULL,
    working_hours_from VARCHAR(255) NULL,
    working_hours_to VARCHAR(255) NULL,
    languages_spoken TEXT NULL,
    PRIMARY KEY (id)
