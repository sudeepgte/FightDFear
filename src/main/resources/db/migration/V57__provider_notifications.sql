    description TEXT NULL,
    location_text TEXT NULL,
    identity_document_path VARCHAR(255) NULL,
    v_status VARCHAR(20) NULL,
    partner_profile_status VARCHAR(40) NULL,
    profile_completion_pct INT NULL DEFAULT 0,
    accepted_terms_at DATETIME NULL,
    submitted_for_verification_at DATETIME NULL,
    rejection_reason TEXT NULL,
    changes_requested_note TEXT NULL,
    reviewed_by_admin_id BIGINT NULL,
    reviewed_by_admin_name VARCHAR(255) NULL,
    reviewed_at DATETIME NULL,
    rating DOUBLE NULL DEFAULT 0,
    practice_areas TEXT NULL,
    bar_council_id VARCHAR(80) NULL,
    experience_years INT NULL,
    languages VARCHAR(255) NULL,
    consultation_fee DOUBLE NULL,
    consultation_mode VARCHAR(40) NULL,
    designation VARCHAR(80) NULL,
    whatsapp_number VARCHAR(32) NULL,
    address VARCHAR(255) NULL,
    city VARCHAR(80) NULL,
    district VARCHAR(100) NULL,
    state VARCHAR(80) NULL,
    pincode VARCHAR(12) NULL,
    country VARCHAR(80) NULL DEFAULT 'India',
    latitude DOUBLE NULL,
    longitude DOUBLE NULL,
    audience VARCHAR(255) NULL,
    door_service BIT(1) NULL,
    facilities TEXT NULL,
    open_days VARCHAR(80) NULL,
    open_time TIME NULL,
    close_time TIME NULL,
    break_start TIME NULL,
    break_end TIME NULL,
    blocked_dates TEXT NULL,
    bio TEXT NULL,
    duration_minutes INT NULL,
    buffer_minutes INT NULL,
    service_mode VARCHAR(24) NULL,
