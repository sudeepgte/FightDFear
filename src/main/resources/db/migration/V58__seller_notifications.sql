CREATE TABLE IF NOT EXISTS women_product_sellers (
    id BIGINT NOT NULL AUTO_INCREMENT,
    full_name VARCHAR(80) NULL,
    email VARCHAR(255) NULL,
    phone VARCHAR(255) NULL,
    password VARCHAR(255) NULL,
    business_name VARCHAR(100) NULL,
    description TEXT NULL,
    address TEXT NULL,
    profile_photo_path VARCHAR(500) NULL,
    identity_doc_path VARCHAR(500) NULL,
    category VARCHAR(100) NULL,
    service_area VARCHAR(255) NULL,
    qualification TEXT NULL,
    experience VARCHAR(100) NULL,
    available_days TEXT NULL,
    working_hours_from VARCHAR(50) NULL,
    working_hours_to VARCHAR(50) NULL,
    languages_spoken TEXT NULL,
    verification_status VARCHAR(255) NULL,
    partner_profile_status VARCHAR(40) NULL,
    profile_completion_pct INT NULL DEFAULT 0,
    accepted_terms_at DATETIME NULL,
    submitted_for_verification_at DATETIME NULL,
    rejection_reason TEXT NULL,
    changes_requested_note TEXT NULL,
    rating DOUBLE NULL DEFAULT 0,
    designation VARCHAR(80) NULL,
    whatsapp_number VARCHAR(32) NULL,
    city VARCHAR(80) NULL,
    state VARCHAR(80) NULL,
    pincode VARCHAR(12) NULL,
    latitude DOUBLE NULL,
    longitude DOUBLE NULL,
    categories_offered TEXT NULL,
    brand_type VARCHAR(40) NULL,
    audience VARCHAR(255) NULL,
    facilities TEXT NULL,
    open_days VARCHAR(80) NULL,
    open_time TIME NULL,
    close_time TIME NULL,
    break_start TIME NULL,
    break_end TIME NULL,
    blocked_dates TEXT NULL,
    bio TEXT NULL,
    dispatch_hours INT NULL,
    typical_price DOUBLE NULL,
    primary_category VARCHAR(40) NULL,
    gstin VARCHAR(32) NULL,
    upi_id VARCHAR(120) NULL,
    bank_details VARCHAR(255) NULL,
    payout_balance DOUBLE NULL,
    payout_requested_at DATETIME NULL,
    gallery_photos TEXT NULL,
    created_at DATETIME NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS seller_notifications (
    id BIGINT NOT NULL AUTO_INCREMENT,
    seller_id BIGINT NOT NULL,
    type VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    order_id BIGINT NULL,
    read_flag BIT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_seller_notif_seller FOREIGN KEY (seller_id) REFERENCES women_product_sellers (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
